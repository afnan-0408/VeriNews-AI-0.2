import streamlit as st

from src.ui import hero, setup_page

setup_page("About", "📘")
hero("About & Methodology", "What this system does, how it is trained, and what it cannot tell you.")

st.header("How it works")
st.markdown("""
1. **TF-IDF** turns each article into a sparse vector: how often each word or word-pair appears, down-weighted when
   the term is common across articles.
2. **Logistic Regression** learns one weight per term. The score is a logistic function of the weighted sum.
3. **Training**: data is split *before* any fitting. TF-IDF and the classifier live in one scikit-learn `Pipeline`
   and are fitted on the training split only, so no information from the test set leaks into the vocabulary.
4. **Evaluation**: metrics come from the held-out test set. Training scores are reported separately.
5. **Explanations**: the per-term bars are the actual `tf-idf value × coefficient` contributions, not generated text.
""")
st.header("Classification is not fact-checking")
st.markdown("""
The model estimates whether an article's *writing patterns* resemble the fake or real examples it was trained on.
It does not check claims against evidence. A true story written sensationally may be scored FAKE; a well-written
falsehood may be scored REAL. Use the output as one weak signal and verify important claims with reliable sources.
Scores are **uncalibrated**: 0.9 does not mean "90% likely to be true".
""")
st.header("Known limitations")
st.markdown("""
- Random splits can overestimate performance if related articles appear in both train and test sets.
- Datasets carry bias (publisher, topic, period). On ISOT the real articles frequently begin with agency tags such as
  “(Reuters) -”, a shortcut that can inflate scores; the training page offers an option to strip them.
- Performance on data from other sources or later periods is usually lower than the held-out numbers.
- The model only works on text in the language and style of its training data.
""")
st.header("Datasets and attribution")
st.markdown("""
- **ISOT Fake News Dataset** (University of Victoria, Information Security and Object Technology lab; Ahmed, Traore &
  Saad). Obtain it from its official source and check the current licence/terms before use. It is not bundled or
  downloaded by this app.
- **Synthetic demo dataset**: generated by `src/demo_data.py` from templates for interface testing only.
- Built with Streamlit, scikit-learn, pandas, NumPy, Plotly, FastAPI and SQLite.
""")
